      url "https://github.com/kazpc1215/safersync-go/releases/download/v#{version}/safersync-#{version}-darwin-amd64.tar.gz"
      sha256 "b1166ea8591214112a491bbbebda4272ceaf0ef4c664f91ebbdc89253c38d99a"
